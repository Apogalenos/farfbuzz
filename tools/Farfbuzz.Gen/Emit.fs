module Farfbuzz.Gen.Emit

open System
open System.Text

/// <summary>The pinned upstream tag and commit in every generated header.</summary>
[<Literal>]
let Tag = "15.1.0"

/// <summary>The pinned upstream commit.</summary>
[<Literal>]
let Commit = "3df40d9b"

/// <summary>Builds the generated-file header.</summary>
/// <param name="sources">The upstream source paths.</param>
/// <returns>The header lines.</returns>
let header (sources: string list) =
    let fileList = String.Join(", ", sources)
    String.Join(
        "\n",
        [ "// <auto-generated>"
          $"// Generated by tools/Farfbuzz.Gen from {fileList} (HarfBuzz {Tag}, commit {Commit})."
          "// Do not edit; run `dotnet run --project tools/Farfbuzz.Gen -- regen`."
          "// </auto-generated>"
          String.Empty ])

/// <summary>Escapes a string for an F# literal.</summary>
/// <param name="text">The text.</param>
/// <returns>The escaped text.</returns>
let private escape (text: string) =
    text.Replace("\\", "\\\\").Replace("\"", "\\\"")

/// <summary>Formats a list of items as a literal array in rows.</summary>
/// <param name="items">The item literals.</param>
/// <param name="perLine">Items per line.</param>
/// <returns>The F# array literal.</returns>
let private arrayLiteral (items: string list) (perLine: int) =
    match items with
    | [] -> "[||]"
    | _ ->
        let rows =
            items
            |> List.chunkBySize perLine
            |> List.map (fun row -> "            " + String.Join("; ", row))
        "[| " + String.Join(";\n", rows) + " |]"

/// <summary>Emits an immutable string array.</summary>
/// <param name="name">The value name.</param>
/// <param name="values">The strings.</param>
/// <returns>The F# binding.</returns>
let strings (name: string) (values: string list) =
    let items = values |> List.map (fun value -> $"\"{escape value}\"")
    $"let {name} : ImmutableArray<string> =\n    Sealed.ofSpan (ReadOnlySpan({arrayLiteral items 6}))"

/// <summary>Emits an immutable array of UTF-8 name byte arrays.</summary>
/// <param name="name">The value name.</param>
/// <param name="values">The strings.</param>
/// <returns>The F# binding.</returns>
let byteArrays (name: string) (values: string list) =
    let byteLiteral (text: string) =
        let bytes = Encoding.UTF8.GetBytes text
        let items = bytes |> Array.map (fun value -> $"{value}uy") |> Array.toList
        "[| " + String.Join("; ", items) + " |]"
    let items = values |> List.map byteLiteral
    $"let {name} : ImmutableArray<byte array> =\n    Sealed.ofSpan (ReadOnlySpan({arrayLiteral items 3}))"

/// <summary>Emits an immutable byte array.</summary>
/// <param name="name">The value name.</param>
/// <param name="values">The bytes.</param>
/// <returns>The F# binding.</returns>
let bytes (name: string) (values: uint32 list) =
    let items = values |> List.map (fun value -> $"{value}uy")
    $"let {name} : ImmutableArray<byte> =\n    Sealed.ofSpan (ReadOnlySpan({arrayLiteral items 16}))"

/// <summary>Emits an immutable uint16 array.</summary>
/// <param name="name">The value name.</param>
/// <param name="values">The values.</param>
/// <returns>The F# binding.</returns>
let uint16s (name: string) (values: uint32 list) =
    let items = values |> List.map (fun value -> $"{value}us")
    $"let {name} : ImmutableArray<uint16> =\n    Sealed.ofSpan (ReadOnlySpan({arrayLiteral items 12}))"

/// <summary>Emits an immutable pair array.</summary>
/// <param name="name">The value name.</param>
/// <param name="values">The pairs.</param>
/// <returns>The F# binding.</returns>
let pairs (name: string) (values: struct (uint32 * uint32) list) =
    let items =
        values
        |> List.map (fun struct (first, second) -> $"struct ({first}us, {second}us)")
    $"let {name} : ImmutableArray<struct (uint16 * uint16)> =\n    Sealed.ofSpan (ReadOnlySpan({arrayLiteral items 6}))"

/// <summary>Emits an immutable uint16/byte pair array.</summary>
/// <param name="name">The value name.</param>
/// <param name="values">The pairs.</param>
/// <returns>The F# binding.</returns>
let bytePairs (name: string) (values: struct (uint16 * byte) list) =
    let items =
        values
        |> List.map (fun struct (first, second) -> $"struct ({first}us, {second}uy)")
    $"let {name} : ImmutableArray<struct (uint16 * byte)> =\n    Sealed.ofSpan (ReadOnlySpan({arrayLiteral items 6}))"

/// <summary>Indents a body under a module declaration with the given access modifier.</summary>
/// <param name="access">The access modifier text placed after the module keyword, empty for public.</param>
/// <param name="name">The module name.</param>
/// <param name="body">The body.</param>
/// <returns>The indented module.</returns>
let moduleBlockWith (access: string) (name: string) (body: string) =
    let indented =
        body.Split('\n')
        |> Array.map (fun line -> match line with | "" -> "" | _ -> "    " + line)
        |> String.concat "\n"
    $"module {access}{name} =\n\n{indented}"

/// <summary>Indents a body under an internal module declaration.</summary>
/// <param name="name">The module name.</param>
/// <param name="body">The body.</param>
/// <returns>The indented module.</returns>
let moduleBlock (name: string) (body: string) = moduleBlockWith "internal " name body

/// <summary>Indents a body under a public module declaration.</summary>
/// <param name="name">The module name.</param>
/// <param name="body">The body.</param>
/// <returns>The indented module.</returns>
let publicModuleBlock (name: string) (body: string) = moduleBlockWith "" name body

/// <summary>Builds a complete generated source file.</summary>
/// <param name="sources">The upstream source paths.</param>
/// <param name="body">The body.</param>
/// <returns>The file text.</returns>
let file (sources: string list) (body: string) =
    header sources + "namespace Farfbuzz\n\nopen System\nopen System.Collections.Immutable\n\n" + body + "\n"
